// Native stand-ins for the THP movie decoder's inverse DCTs (the Dolphin SDK's THP library; Twilight Princess links it
// into d_a_movie_player.rel and loads it at run time): __THPInverseDCTNoYPos and __THPInverseDCTY8, 28.7% and 15.3% of
// core 0 during the attract movie (2DS job 289, the module's symbols from zeldaret/tp placed at the loaded base). Each
// call turns one 8x8 block of s16 coefficients into 64 u8 samples in the locked cache: rows (dequantised with the float
// table Gq, four paths by which coefficients are zero) into a float workspace, then columns with a bias of 1024, stored
// with GQR6 (u8, scale 2^-3: truncated toward zero, clamped to 0-255). Paired-single code, the JIT's slowest kind (2DS
// job 279: ps_madd 59 cycles, psq_st u8 87 per guest instruction).
//
// The stand-in is the module's own compiled code as C (hle_thp_idct.inc, generated by core/tools/thp_translate.py from
// the disc's REL: the decompilation's asm is scheduled differently, and some paths of it count other instruction
// totals), each paired-single operation computed as gc3ds's JIT does, which its fuzzer holds equal to the interpreter:
// add, sub and mul in single precision (for single inputs the same as double then single), the multiply-adds in double
// then rounded to single, quantised stores as the interpreter's quantize. Every value here is a single (loads of floats and
// s16, results of ps operations), so the multiply's 25-bit frC cut never changes one. It writes what the guest writes
// (the workspace and the samples) and returns to LR; volatile registers and the callee's stack frame are dead state
// (owner decision 2026-10-15). HLE_CHECK=1 (PC) compares the samples and the workspace with the interpreter.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "gekko_internal.h"
#include "hle.h"

typedef struct { float p0, p1; } P;  // ps0, ps1
static inline P PS(float v) { P p = { v, v }; return p; }
#define PADD(x, y) ((P){ (x).p0 + (y).p0, (x).p1 + (y).p1 })
#define PSUB(x, y) ((P){ (x).p0 - (y).p0, (x).p1 - (y).p1 })
#define PMUL(x, c) ((P){ (x).p0 * (c).p0, (x).p1 * (c).p1 })
static inline float madd1(float a, float c, float b) { return (float)((double)a * (double)c + (double)b); }
static inline float msub1(float a, float c, float b) { return (float)((double)a * (double)c - (double)b); }
#define PMADD(a, c, b) ((P){ madd1((a).p0, (c).p0, (b).p0), madd1((a).p1, (c).p1, (b).p1) })
#define PMSUB(a, c, b) ((P){ msub1((a).p0, (c).p0, (b).p0), msub1((a).p1, (c).p1, (b).p1) })
#define PNMSUB(a, c, b) ((P){ -msub1((a).p0, (c).p0, (b).p0), -msub1((a).p1, (c).p1, (b).p1) })
#define PMERGE00(x, y) ((P){ (x).p0, (y).p0 })
#define PMERGE01(x, y) ((P){ (x).p0, (y).p1 })
#define PMERGE10(x, y) ((P){ (x).p1, (y).p0 })
#define PMERGE11(x, y) ((P){ (x).p1, (y).p1 })

static u8* g_m;      // MEM1
static u32 g_size;
static u8* g_lc;     // the locked cache (16 KB at 0xE0000000)

// Guest addresses, already checked (thp_run): MEM1 through either mapping, or the locked cache.
static inline u8* hp(u32 ea) { return (ea >> 24) == 0xE0 ? g_lc + (ea & 0x3FFF) : g_m + (ea & 0x01FFFFFF); }
static inline u32 be32(const u8* p) { return (u32)p[0] << 24 | (u32)p[1] << 16 | (u32)p[2] << 8 | p[3]; }
#define LD32(a) be32(hp(a))
#define LD16(a) ((u32)hp(a)[0] << 8 | hp(a)[1])
static inline float ldf(u32 ea) { u32 w = LD32(ea); float f; memcpy(&f, &w, 4); return f; }
static inline void stf(u32 ea, float f) { u32 w; memcpy(&w, &f, 4); u8* p = hp(ea); p[0] = (u8)(w >> 24); p[1] = (u8)(w >> 16); p[2] = (u8)(w >> 8); p[3] = (u8)w; }
static inline float lds16(u32 ea) { return (float)(s16)LD16(ea); }
static inline u8 qu8(float v) {  // GQR6's store: u8, scale -3 (the interpreter's quantize: truncate toward zero, saturate)
    double x = (double)v * 0.125;
    if (x != x) return 0;
    if (x <= 0.0) return 0;
    if (x >= 255.0) return 255;
    return (u8)(u32)x;
}
#define LDF2(a) ((P){ ldf(a), ldf((a) + 4) })
#define LDS16X2(a) ((P){ lds16(a), lds16((a) + 2) })
#define STF2(a, v) do { u32 a_ = (a); P v_ = (v); stf(a_, v_.p0); stf(a_ + 4, v_.p1); } while (0)
#define STU8X2(a, v) do { u32 a_ = (a); P v_ = (v); u8* p_ = hp(a_); p_[0] = qu8(v_.p0); p_[1] = qu8(v_.p1); } while (0)

#include "hle_thp_idct.inc"

// The two functions, at .text offsets 0x18DC and 0x1D7C of d_a_movie_player.rel (zeldaret/tp symbols; the module's load
// address varies). Both start the same way: a 0x70-byte frame saving f26-f31 (stfd and psq_st), the module's .rodata
// and .bss bases (lis+addi each, the only words the loader relocates), the five constants (lfs at .rodata+0x98..0xa8),
// Gq (lwz at .bss+0x5e4) and the workspace (addi .bss+0x4c0); between the passes the workspace again, Gbase (.bss+0x5cc)
// and Gwid (.bss+0x5e0). Recognised at a PC whose first word and the asm's first word (+0x6c) match, by a hash of the
// bytes with the relocated immediates zeroed, then by reading the bases back and checking the constants' values.
#define THP_FIRST 0x9421FF90u  // stwu r1,-0x70(r1)
#define THP_SIG 0xE1435000u    // +0x6c: psq_l f10,0(r3),0,5 (the first row's coefficients)
typedef struct {
    const char* name;
    u32 size;     // bytes
    u64 hash;     // FNV-1a 64 of the masked bytes (0: print it with HLE_PRINT_HASH and refuse)
    bool y8;
} ThpDef;
static const ThpDef g_def[2] = {
    { "__THPInverseDCTY8", 0x4A0, 0x9826E3D7C211C4C6ull, true },
    { "__THPInverseDCTNoYPos", 0x498, 0x888DCD0CDCE3A4E5ull, false },
};
typedef struct { u32 pc, ws, bss, rodata; s8 def; } ThpFn;  // a recognised copy (ws: the workspace, .bss + 0x4c0)
static ThpFn g_fn[4];
static u32 g_nfn;
#define NEG 16
static u32 g_neg[NEG];  // PCs whose first word matched and the rest did not (a small cache; 0 empty)
static bool g_thpOn = true;
u64 g_thpStats[3];      // calls, guest instructions stood in for, refused (an address the stand-in does not take)

void hle_thp_set_memory(u8* mem1, u32 size, u8* lc) { g_m = mem1; g_size = size; g_lc = lc; g_nfn = 0; memset(g_neg, 0, sizeof g_neg); }
void hle_thp_invalidate(u32 pa) {
    for (u32 k = 0; k < g_nfn;) {
        u32 lo = g_fn[k].pc & 0x0FFFFFFFu, hi = lo + g_def[g_fn[k].def].size - 1;
        if (pa >> 12 >= lo >> 12 && pa >> 12 <= hi >> 12) g_fn[k] = g_fn[--g_nfn]; else k++;
    }
    for (u32 k = 0; k < NEG; k++) if ((g_neg[k] & 0x0FFFFFFFu) >> 12 == pa >> 12) g_neg[k] = 0;
}
void hle_thp_set_enabled(bool on) { g_thpOn = on; }
bool hle_thp_enabled(void) { return g_thpOn; }

// MEM1 through the cached or uncached mapping, or the locked cache: the host address of [ea, ea+len), or NULL.
static u8* region(u32 ea, u32 len) {
    u32 top = ea >> 28;
    if (top == 0x8 || top == 0xC) { u32 pa = ea & 0x0FFFFFFFu; return pa + len <= g_size && pa + len >= pa ? g_m + pa : NULL; }
    if (ea >= 0xE0000000u && ea + len <= 0xE0004000u && ea + len >= ea && g_lc) return g_lc + (ea & 0x3FFF);
    return NULL;
}

static u32 rdw(u32 pa) { return be32(g_m + pa); }

static bool recognise(u32 pc, int d, ThpFn* out) {
    const ThpDef* f = &g_def[d];
    u32 pa = pc & 0x0FFFFFFFu;
    if (!g_m || pa + f->size > g_size) return false;
    u64 h = 0xCBF29CE484222325ull;
    for (u32 i = 0; i < f->size; i += 4) {
        u32 w = rdw(pa + i);
        if (i >= 0x34 && i < 0x44) w &= 0xFFFF0000u;  // lis r5 / addi r6,r5 (.rodata), lis r5 / addi r5,r5 (.bss)
        for (int b = 24; b >= 0; b -= 8) { h ^= (u8)(w >> b); h *= 0x100000001B3ull; }
    }
#ifndef __3DS__
    if (getenv("HLE_PRINT_HASH")) fprintf(stderr, "HLE hash of %s at %08x: %016llx\n", f->name, pc, (unsigned long long)h);
#endif
    if (!f->hash || h != f->hash) return false;
    u32 rodata = (rdw(pa + 0x34) << 16) + (u32)(s32)(s16)rdw(pa + 0x38), bss = (rdw(pa + 0x3C) << 16) + (u32)(s32)(s16)rdw(pa + 0x40);
    u32 ws = bss + 0x4C0;
    static const u32 want[5] = { 0x3FB504F3u, 0x3FEC835Eu, 0x3F8A8BD4u, 0xC0273D75u, 0x44800000u };  // cc4 cc2 cc2c6s cc2c6a bias
    u8* c = region(rodata + 0x98, 20);
    if (!c || (ws & 7) || !region(ws - 8, 0x12C)) return false;
    for (u32 k = 0; k < 5; k++) if (be32(c + 4 * k) != want[k]) return false;
    out->pc = pc; out->ws = ws; out->bss = bss; out->rodata = rodata; out->def = (s8)d;
#ifndef __3DS__
    if (getenv("HLE_CHECK")) fprintf(stderr, "HLE_CHECK %s recognised at %08x: workspace %08x\n", f->name, pc, ws);
#endif
    return true;
}

static ThpFn* thp_find(u32 pc) {
    for (u32 k = 0; k < g_nfn; k++) if (g_fn[k].pc == pc) return &g_fn[k];
    u32 pa = pc & 0x0FFFFFFFu, top = pc >> 28;
    if ((top != 0x8 && top != 0xC) || (pc & 3) || !g_m || pa + 0x70 > g_size || rdw(pa) != THP_FIRST || rdw(pa + 0x6C) != THP_SIG) return NULL;
    for (u32 k = 0; k < NEG; k++) if (g_neg[k] == pc) return NULL;
    ThpFn f;
    for (int d = 0; d < 2; d++)
        if (g_nfn < 4 && recognise(pc, d, &f)) { g_fn[g_nfn++] = f; return &g_fn[g_nfn - 1]; }
    static u32 next;
    g_neg[next++ % NEG] = pc;
    return NULL;
}

bool hle_thp_is_hook(u32 pc) { return g_thpOn && thp_find(pc) != NULL; }

static u32 thp_native(Gekko* g) {
    ThpFn* f = thp_find(g->pc);
    if (!f) return 0;
    // The state the C assumes: the FPU on (with it off, as the OS leaves it after a thread switch, the first FP
    // instruction traps to load the thread's FP registers: HLE_CHECK, 112 of 957,600 calls), round to nearest, paired
    // singles and their loads / stores on, GQR5 loading s16 and GQR6 storing u8 at scale -3, data translation on.
    if ((g->msr & (MSR_DR | MSR_FP)) != (MSR_DR | MSR_FP) || (g->fpscr & FPSCR_RN) ||
        (g->spr[SPR_HID2] & (HID2_PSE | HID2_LSQE)) != (HID2_PSE | HID2_LSQE) || g->spr[SPR_GQR0 + 5] >> 16 != 0x0007u ||
        (g->spr[SPR_GQR0 + 6] & 0xFFFFu) != 0x3D04u) { g_thpStats[2]++; return 0; }
    u32 ws = f->ws;
    u8* gp = region(ws + 0x10C, 0x1C);
    if (!gp) return 0;
    u32 base = be32(gp), wid = be32(gp + 0x14), q = be32(gp + 0x18), in = g->gpr[3], xPos = g->gpr[4];
    u32 off0 = (g_def[f->def].y8 ? wid << 3 : 0) + (xPos << 2);
    // Everything the guest would touch, checked here once: then the accesses need no checks of their own.
    if (!region(in, 128) || !region(q, 256) || !region(ws - 8, 264) || wid > 0x10000 || xPos > 0x10000 ||
        !region(base + off0, (wid << 2) + 32)) { g_thpStats[2]++; return 0; }
    u32 n = g_def[f->def].y8 ? idct_y8(in, xPos, f->bss, f->rodata) : idct_noy(in, xPos, f->bss, f->rodata);
    g->pc = g->lr;
    g_thpStats[0]++;
    g_thpStats[1] += n;
    return n;
}

#ifndef __3DS__
// HLE_CHECK=1: every call also runs in the interpreter from the same state for the same instruction count; compared:
// PC, LR, r1, r2, r13-r31, f14-f31 (both halves), CR fields 2-4, the workspace and the 8x8 samples. The interpreter's
// result stands.
static struct { u64 calls, bad; } g_tchk;
static void tchk_report(void) {
    fprintf(stderr, "HLE_CHECK (THP IDCT): %llu stand-in calls compared with the interpreter, %llu differed\n",
            (unsigned long long)g_tchk.calls, (unsigned long long)g_tchk.bad);
}
static u32 thp_checked(Gekko* g) {
    ThpFn* f = thp_find(g->pc);
    if (!f) return 0;
    const char* name = g_def[f->def].name;
    u32 ws = f->ws;
    u8* gp = region(ws + 0x10C, 0x1C);
    if (!gp) return 0;
    u32 base = be32(gp), wid = be32(gp + 0x14), xPos = g->gpr[4];
    u32 off0 = (g_def[f->def].y8 ? wid << 3 : 0) + (xPos << 2), olen = (wid << 2) + 32;
    u8* o = region(base + off0, olen);
    u8* w = region(ws - 8, 264);
    if (!o || !w || olen > 4096) return 0;
    static u8 o0[4096], oN[4096], w0[264], wN[264];
    Gekko g0 = *g;
    memcpy(o0, o, olen); memcpy(w0, w, 264);
    u32 n = thp_native(g);
    if (!n) return 0;
    Gekko gn = *g;
    memcpy(oN, o, olen); memcpy(wN, w, 264);
    *g = g0;
    memcpy(o, o0, olen); memcpy(w, w0, 264);
    u32 steps = 0;
    while (steps < n) {
        u32 pa = g->pc & 0x0FFFFFFFu;
        if (pa + 4 > g_size) break;
        bool stop;
        g->pc = gekko_interp_one(g, g->pc, rdw(pa), &stop);
        steps++;
    }
    if (!g_tchk.calls++) atexit(tchk_report);
    bool same = steps == n && g->pc == gn.pc && g->lr == gn.lr && g->gpr[1] == gn.gpr[1] && g->gpr[2] == gn.gpr[2] &&
                !memcmp(&g->gpr[13], &gn.gpr[13], 19 * 4) && !memcmp(&g->fpr[14], &gn.fpr[14], 18 * sizeof(FPR)) &&
                (g->cr & 0x00FFF000u) == (gn.cr & 0x00FFF000u) && !memcmp(o, oN, olen) && !memcmp(w, wN, 264);
    if (!same && g_tchk.bad++ < 20) {
        fprintf(stderr, "HLE_CHECK %s call %llu: native %u insns to %08x, interpreter %u to %08x\n", name,
                (unsigned long long)g_tchk.calls, n, gn.pc, steps, g->pc);
        for (u32 k = 0; k < olen; k++)
            if (o[k] != oN[k]) { fprintf(stderr, "  sample +%u: native %02x interpreter %02x\n", k, oN[k], o[k]); break; }
        for (u32 k = 0; k < 264; k++)
            if (w[k] != wN[k]) { fprintf(stderr, "  workspace +%u: native %02x interpreter %02x\n", k, wN[k], w[k]); break; }
        for (int k = 14; k < 32; k++)
            if (memcmp(&g->fpr[k], &gn.fpr[k], sizeof(FPR))) fprintf(stderr, "  f%d native %g/%g interpreter %g/%g\n", k, gn.fpr[k].ps0, gn.fpr[k].ps1, g->fpr[k].ps0, g->fpr[k].ps1);
    }
    return steps;
}
#endif

u32 hle_thp_run(Gekko* g) {
    if (!g_thpOn) return 0;
#ifndef __3DS__
    static int chk = -1;
    if (chk < 0) chk = getenv("HLE_CHECK") != NULL;
    if (chk) return thp_checked(g);
#endif
    return thp_native(g);
}
