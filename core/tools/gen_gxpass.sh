#!/usr/bin/env bash
# Generates core/src/gx/pica/gxpass.v.pica, the GX backend's vertex shader: eight unrolled light blocks (picasso has
# no macros). The maths is gx/vfast.c's vfast_gpu_light_model, which VFAST_CHECK compares with the reference.
#   bash core/tools/gen_gxpass.sh
# With `native`, core/src/gx/pica/gxpass_native.v.pica instead: the same shader plus native mode's converted-shape path
# (gx/pica/pica.c, NATIVE_PORT_PLAN.md "Converted shapes"), selected per draw with the uniform nat.x = 1. Only
# native builds (core/native/Makefile) use it; the emulator's shader is unchanged.
set -euo pipefail
native=0
[ "${1:-}" = native ] && native=1
if [ $native = 1 ]; then out="$(dirname "$0")/../src/gx/pica/gxpass_native.v.pica"; else out="$(dirname "$0")/../src/gx/pica/gxpass.v.pica"; fi
{
cat <<'EOF'
; gc3ds GX backend vertex shader (generated by core/tools/gen_gxpass.sh; edit that).
; v0 is the position. With lon.w = 1 the shader transforms it (gx/vfast.c vfast_job_gpu_pos): v0.xyz relative to the
; draw's origin, which the palette matrices carry in their translation (vfast_job_origin),
; v0.w = 3 * the palette slot of its position matrix, clip = proj * (pal[v0.w .. v0.w + 2] * v0.xyz), as
; vfast_gpu_pos_model (the C model the PC checks against the reference); otherwise v0 is the clip position the CPU
; computed. v1 colour (u8x4), v2-v4 texture coordinates.
; With lon.z = 1 the shader lights the colour channel the PICA receives, from the eight GX lights, exactly as
; vfast_gpu_light_model, for the cases vfast_gpu_light sends: colour half lit with attenuation none or spot, alpha
; half unlit or lit as the colour half. v1 is then the raw vertex colour and v6 the eye-space normal (normalised
; here); the eye-space position is the shader's own (lon.w = 1) or v5. Uniform layout: VLightUniforms in gx/vfast.h.
; Float uniforms: 48 lighting + 4 projection + 42 palette (14 matrices) + 1 constant, of the PICA's 96.

.fvec lights[40]
.fvec lsel[4]
.fvec lmat, lamb, lvsel, lon  ; lon: (colour half lit, alpha half lit, light this batch, transform this batch)
.fvec proj[4]
.fvec pal[42]
EOF
if [ $native = 1 ]; then cat <<'EOF'
.fvec nat     ; native mode: nat.x = 1 for a converted shape (procedure native below)
.ivec lcount  ; native mode: the lights the native path loops over (count - 1, first, step 5)
EOF
fi
cat <<'EOF'


.constf myconst(0.0, 1.0, 0.00392156862745098, 1.0e18)
.alias  zeros  myconst.xxxx
.alias  ones   myconst.yyyy
.alias  inv255 myconst.zzzz
.alias  big    myconst.wwww  ; reciprocals are clamped to +-big: an unused term must stay finite so that 0 * it is 0

.out outpos position
.out outclr color
.out outtc0 texcoord0
.out outtc1 texcoord1
.out outtc2 texcoord2

.proc main
EOF
# The native path is a conditional call that ends the shader itself: an ifc / .else around the main path would need an
# else block of ~300 instructions, and the PICA's IFC holds the else length in 8 bits (picasso truncated it silently).
if [ $native = 1 ]; then cat <<'EOF'
	mov r14, ones
	cmp nat.xxxx, eq, eq, r14
	callc cmp.x, native
EOF
fi
cat <<'EOF'
	; float flags tested with cmp (a bool uniform did not reach the shader): cmp.x lon.z = 1, the shader lights this
	; batch; cmp.y lon.w = 1, it transforms this batch. r6 holds the eye-space position for the lighting.
	mov r14, ones
	cmp lon.zwzw, eq, eq, r14
	ifc cmp.y
	mova a0.x, v0.w
	mov r6.xyz, v0.xyz
	mov r6.w, ones
	dp4 r5.x, pal[a0.x], r6
	dp4 r5.y, pal[a0.x+1], r6
	dp4 r5.z, pal[a0.x+2], r6
	mov r5.w, ones
	dp4 outpos.x, proj[0], r5
	dp4 outpos.y, proj[1], r5
	dp4 outpos.z, proj[2], r5
	dp4 outpos.w, proj[3], r5
	mov r6, r5
	.else
	mov outpos, v0
	mov r6, v5
	.end
	mov outtc0, v2
	mov outtc1, v3
	mov outtc2, v4
	mul r15, inv255, v1
	ifc cmp.x
	mov r10.xyz, v6
	mov r10.w, zeros
	dp3 r0.x, r10, r10
	rsq r0.x, r0.x
	min r0.x, big, r0.x
	mul r10.xyz, r10.xyz, r0.xxxx
	mov r11, zeros
EOF
# One light's contribution up to its factor in r13.x; $1, $2, $4, $5: the uniform operands of its position,
# direction, angle and distance terms.
light_body() {
    cat <<EOF2
	add r0, $1, -r6
	dp3 r1.x, r0, r0
	rsq r1.y, r1.x
	min r1.y, big, r1.y
	mul r1.z, r1.x, r1.y
	mul r0, r0, r1.yyyy
	dp3 r2.x, r10, r0
	max r2.y, zeros, r2.x
	dp3 r2.z, -$2, r0
	mov r3.x, ones
	mov r3.y, r2.z
	mul r3.z, r2.z, r2.z
	dp3 r4.x, $4, r3
	max r4.x, zeros, r4.x
	mov r5.x, ones
	mov r5.y, r1.z
	mov r5.z, r1.x
	dp3 r4.y, $5, r5
	rcp r7.x, r4.y
	min r7.x, big, r7.x
	max r7.x, -big, r7.x
	mul r7.z, r4.x, r7.x
	mov r8.x, ones
	mov r8.y, r2.x
	mov r8.z, r2.y
	mov r9.x, ones
	mov r9.y, r7.z
	mov r9.z, zeros
	dp3 r12.x, lsel[0], r8
	dp3 r12.y, lsel[1], r9
	mul r13.x, r12.x, r12.y
	mul r13.x, $4.wwww, r13.x
EOF2
}
for i in 0 1 2 3 4 5 6 7; do
    P=$((5 * i)); D=$((P + 1)); C=$((P + 2)); A=$((P + 3)); K=$((P + 4))
    cat <<EOF2
	; ---- light $i: L, distance, diffuse, spot attenuation (vfast_gpu_light only sends attenuation none or spot, and an
	; alpha half that is unlit or lit exactly as the colour half, so one factor lights all four components)
EOF2
    light_body "lights[$P]" "lights[$D]" "lights[$C]" "lights[$A]" "lights[$K]"
    echo "	mad r11, r13.xxxx, lights[$C], r11"
done
cat <<'EOF'
	; material and ambient from the register or the vertex colour; lit halves clamp ambient + lights to 0..1
	add r0, -lmat, r15
	mul r1, lvsel.xxxy, r0
	add r1, lmat, r1
	add r0, -lamb, r15
	mul r2, lvsel.zzzw, r0
	add r2, lamb, r2
	add r3, r2, r11
	max r3, zeros, r3
	min r3, ones, r3
	add r3, -ones, r3
	mul r3, lon.xxxy, r3
	add r3, ones, r3
	mul outclr, r1, r3
	.else
	mov outclr, r15
	.end
EOF
cat <<'EOF'
	end
.end
EOF
if [ $native = 1 ]; then
cat <<'EOF'

; Native mode's converted shapes (pica.c): v0.xyz the vertex relative to its shape's origin, v0.w the XF row of its
; position matrix; pal[row .. row + 2] hold that matrix with the origin folded into its translation. v6 the model-space
; normal, to eye space through the position matrix's 3x3 and normalised (exact for rotation and uniform scale). v1 the
; vertex colour (u8x4). v2-v4: texture unit u's texgen input (x, y, z; w = 1), its matrix rows pal[30 + 3u ..], s and t
; divided by q (rows set so that q = 1 without stq). Lighting as the main path's, over the lcount lights packed at the
; front of lights[]; unlit, the colour is the material (lmat, or the vertex colour by lvsel).
.proc native
	mova a0.x, v0.w
	mov r6.xyz, v0.xyz
	mov r6.w, ones
	dp4 r5.x, pal[a0.x], r6
	dp4 r5.y, pal[a0.x+1], r6
	dp4 r5.z, pal[a0.x+2], r6
	mov r5.w, ones
	dp4 outpos.x, proj[0], r5
	dp4 outpos.y, proj[1], r5
	dp4 outpos.z, proj[2], r5
	dp4 outpos.w, proj[3], r5
	mov r6, r5
EOF
for u in 0 1 2; do
    R=$((30 + 3 * u)); V=$((2 + u))
    cat <<EOF2
	mov r7.xyz, v$V
	mov r7.w, ones
	dp4 r8.x, pal[$R], r7
	dp4 r8.y, pal[$((R + 1))], r7
	dp4 r8.z, pal[$((R + 2))], r7
	rcp r8.z, r8.z
	min r8.z, big, r8.z
	max r8.z, -big, r8.z
	mul outtc$u, r8.xyyy, r8.zzzz
EOF2
done
cat <<'EOF'
	mul r15, inv255, v1
	cmp lon.zzzz, eq, eq, r14
	ifc cmp.x
	dp3 r10.x, pal[a0.x], v6
	dp3 r10.y, pal[a0.x+1], v6
	dp3 r10.z, pal[a0.x+2], v6
	mov r10.w, zeros
	dp3 r0.x, r10, r10
	rsq r0.x, r0.x
	min r0.x, big, r0.x
	mul r10.xyz, r10.xyz, r0.xxxx
	mov r11, zeros
	for lcount
EOF
light_body "lights[aL]" "lights[aL+1]" "lights[aL+2]" "lights[aL+3]" "lights[aL+4]"
cat <<'EOF'
	mul r12, lights[aL+2], r13.xxxx
	add r11, r11, r12
	.end
	add r0, -lamb, r15
	mul r2, lvsel.zzzw, r0
	add r2, lamb, r2
	add r3, r2, r11
	max r3, zeros, r3
	min r3, ones, r3
	add r3, -ones, r3
	mul r3, lon.xxxy, r3
	add r3, ones, r3
	add r0, -lmat, r15
	mul r1, lvsel.xxxy, r0
	add r1, lmat, r1
	mul outclr, r1, r3
	.else
	add r0, -lmat, r15
	mul r1, lvsel.xxxy, r0
	add r1, lmat, r1
	mov outclr, r1
	.end
	end
.end
EOF
fi
} > "$out"
echo "wrote $out ($(grep -c . "$out") lines)"
