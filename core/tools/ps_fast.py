#!/usr/bin/env python3
"""Derive X3 entry-operand variants from the existing translated C; needs no disc or disassemblies.

The original functions remain byte-identical. Only entry loads use explicit arguments; loads after nested calls
still read guest state. Shared macro definitions and each function's body come from the same source chunk.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'src/cpu/hle_ps_gen.inc'
TARGET = ROOT/'src/cpu/hle_ps_fast.inc'
GROUPS = ('GXSetTev', 'GXSetChanCtrl', 'GXSetArray', '__GXSetMatrixIndex', '__pl', '__mi', '__ml')


def generate():
    source = SOURCE.read_text()
    names = re.findall(r'^    \{ "([^"]+)"', source, re.M)
    output = ['// Generated by core/tools/ps_fast.py from hle_ps_gen.inc; do not edit.\n']
    definitions = []
    previous_end = source.index('#define')
    for match in re.finditer(r'static u32 ps_(\w+)\(Gekko\* g\)', source):
        name = match[1]
        end = source.index('\n}\n', match.end())+3
        chunk = source[previous_end:end]
        previous_end = end
        if not name.startswith(GROUPS):
            continue
        prefix, body = chunk.split('    n++;', 1)
        at = prefix.index(f'static u32 ps_{name}(')
        macros, entry = prefix[:at], prefix[at:]
        inputs = sum(1 << k for k in set(map(int, re.findall(r'g->gpr\[(\d+)\]', entry))))
        entry = re.sub(r'g->gpr\[(\d+)\]', r'a->gpr[\1]', entry)
        entry = entry.replace('g->cr', 'a->cr').replace('g->xer', 'a->xer')
        entry = entry.replace(f'ps_{name}(Gekko* g)', f'ps_fast_{name}(Gekko* g, const HleFastArgs* a)')
        prefix = macros+entry
        chunk = prefix+'    n++;'+body
        # The next chunk owns the #undefs. Copy them here too, so skipping functions cannot leak their macros.
        post = source[end:]
        cleanup = re.match(r'(?:#undef[^\n]*\n)*', post)[0]
        output.append(chunk+cleanup)
        written = sum(1 << k for k in set(map(int, re.findall(r'g->gpr\[(\d+)\]\s*=', body))))
        fpread = sum(1 << k for k in set(map(int, re.findall(r'(?:FIN|S2S|F2S)\((\d+)\)', chunk))))
        fpwritten = sum(1 << k for k in set(map(int, re.findall(r'g->fpr\[(\d+)\]\.ps[01]\s*=', chunk))))
        group = 'HLE_FAST_XYZ' if name.startswith(('__pl', '__mi', '__ml')) else 'HLE_FAST_GX'
        definitions.append((name, inputs, written, fpread, fpwritten, group))
    output.append('static const PsFastDef g_psFast[] = {\n')
    for name, inputs, written, fpread, fpwritten, group in definitions:
        output.append(f'    {{ {names.index(name)}, ps_fast_{name}, {inputs:#010x}u, {written:#010x}u, '
                      f'{fpread:#x}u, {fpwritten:#x}u, {group} }},\n')
    output.append('};\n')
    return ''.join(output)


if __name__ == '__main__':
    import sys
    generated = generate()
    if '--check' in sys.argv:
        if '--plant' in sys.argv:
            generated += '// deliberately different entry-operand variant\n'
        assert TARGET.read_text() == generated, 'regenerate with core/tools/ps_fast.py'
        print('PS fast entry variants match the existing translated functions')
    else:
        TARGET.write_text(generated)
